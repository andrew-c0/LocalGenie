const MAX_NAME_CHARS: usize = 120;
const MAX_DESCRIPTION_CHARS: usize = 2000;
const MAX_STEPS: usize = 50;
const MAX_FILES_PER_STEP: usize = 10;
const MAX_WARMUP_RUNS: i32 = 10;
const MAX_REPETITIONS: i32 = 20;

/// A suite as the editor needs it: its steps in order, with each step's prompt and files.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkSuiteDto {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
    pub mode: String,
    pub warmup_runs: i32,
    pub repetitions: i32,
    /// Runs since the suite was last saved.
    pub run_count: i64,
    pub steps: Vec<BenchmarkSuiteStepDto>,
    pub created_at: i64,
    pub updated_at: i64,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkSuiteStepDto {
    pub id: String,
    pub prompt_id: String,
    pub prompt_name: String,
    /// The prompt's own files, sent with the step.
    pub prompt_files: Vec<BenchmarkFileDto>,
    /// Extra files for this step only.
    pub files: Vec<BenchmarkFileDto>,
}

/// What the editor sends. Ids are generated by the frontend; a save replaces the suite's steps.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkSuiteInput {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
    pub mode: String,
    pub warmup_runs: i32,
    pub repetitions: i32,
    pub steps: Vec<BenchmarkSuiteStepInput>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkSuiteStepInput {
    pub id: String,
    pub prompt_id: String,
    pub file_ids: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
struct ValidSuite {
    id: String,
    name: String,
    description: Option<String>,
    mode: String,
    warmup_runs: i32,
    repetitions: i32,
    steps: Vec<ValidStep>,
}

#[derive(Debug, Clone, PartialEq)]
struct ValidStep {
    id: String,
    prompt_id: String,
    file_ids: Vec<String>,
}

#[tauri::command]
pub async fn list_benchmark_suites(
    db: State<'_, DatabaseConnection>,
) -> Result<Vec<BenchmarkSuiteDto>, String> {
    list_suites(&db).await
}

#[tauri::command]
pub async fn save_benchmark_suite(
    app: AppHandle,
    db: State<'_, DatabaseConnection>,
    suite: BenchmarkSuiteInput,
) -> Result<BenchmarkSuiteDto, String> {
    let root = store_root(&app)?;
    save_suite(&db, &root, suite).await
}

#[tauri::command]
pub async fn delete_benchmark_suite(
    app: AppHandle,
    db: State<'_, DatabaseConnection>,
    id: String,
) -> Result<(), String> {
    let root = store_root(&app)?;
    delete_suite(&db, &root, &id).await
}

async fn list_suites(db: &DatabaseConnection) -> Result<Vec<BenchmarkSuiteDto>, String> {
    let suites = benchmark_suite::Entity::find()
        .order_by_asc(benchmark_suite::Column::Name)
        .all(db)
        .await
        .map_err(|e| e.to_string())?;
    let mut out = Vec::with_capacity(suites.len());
    for suite in suites {
        out.push(load_suite(db, suite).await?);
    }
    Ok(out)
}

async fn load_suite(
    db: &DatabaseConnection,
    suite: benchmark_suite::Model,
) -> Result<BenchmarkSuiteDto, String> {
    let step_rows = benchmark_suite_step::Entity::find()
        .filter(benchmark_suite_step::Column::SuiteId.eq(&suite.id))
        .order_by_asc(benchmark_suite_step::Column::Position)
        .all(db)
        .await
        .map_err(|e| e.to_string())?;

    let mut steps = Vec::with_capacity(step_rows.len());
    for step in step_rows {
        let prompt = benchmark_prompt::Entity::find_by_id(step.prompt_id.as_str())
            .one(db)
            .await
            .map_err(|e| e.to_string())?
            .ok_or_else(|| format!("prompt {} is missing", step.prompt_id))?;

        let prompt_file_ids: Vec<String> = benchmark_prompt_file::Entity::find()
            .filter(benchmark_prompt_file::Column::PromptId.eq(&step.prompt_id))
            .order_by_asc(benchmark_prompt_file::Column::Position)
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|l| l.file_id)
            .collect();

        let step_file_ids: Vec<String> = benchmark_step_file::Entity::find()
            .filter(benchmark_step_file::Column::StepId.eq(&step.id))
            .order_by_asc(benchmark_step_file::Column::Position)
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|l| l.file_id)
            .collect();

        steps.push(BenchmarkSuiteStepDto {
            id: step.id,
            prompt_id: step.prompt_id,
            prompt_name: prompt.name,
            prompt_files: load_files(db, &prompt_file_ids).await?,
            files: load_files(db, &step_file_ids).await?,
        });
    }

    Ok(BenchmarkSuiteDto {
        id: suite.id,
        name: suite.name,
        description: suite.description,
        mode: suite.mode,
        warmup_runs: suite.warmup_runs,
        repetitions: suite.repetitions,
        run_count: suite.run_count,
        steps,
        created_at: suite.created_at,
        updated_at: suite.updated_at,
    })
}

/// Every file a suite's steps hold, so a save or delete can remove the ones it drops.
async fn step_file_ids_of_suite(
    db: &DatabaseConnection,
    suite_id: &str,
) -> Result<Vec<String>, String> {
    let step_ids: Vec<String> = benchmark_suite_step::Entity::find()
        .filter(benchmark_suite_step::Column::SuiteId.eq(suite_id))
        .all(db)
        .await
        .map_err(|e| e.to_string())?
        .into_iter()
        .map(|s| s.id)
        .collect();
    if step_ids.is_empty() {
        return Ok(Vec::new());
    }
    let links = benchmark_step_file::Entity::find()
        .filter(benchmark_step_file::Column::StepId.is_in(step_ids))
        .all(db)
        .await
        .map_err(|e| e.to_string())?;
    let mut ids: Vec<String> = links.into_iter().map(|l| l.file_id).collect();
    ids.sort();
    ids.dedup();
    Ok(ids)
}

/// Create or replace a suite and its steps. Files dropped by the save are removed from disk when
/// nothing else uses them. Testable core of `save_benchmark_suite`.
pub(super) async fn save_suite(
    db: &DatabaseConnection,
    root: &Path,
    input: BenchmarkSuiteInput,
) -> Result<BenchmarkSuiteDto, String> {
    let valid = validate(input)?;
    let now = now_millis();

    let previous_files = step_file_ids_of_suite(db, &valid.id).await?;
    let existing = benchmark_suite::Entity::find_by_id(valid.id.as_str())
        .one(db)
        .await
        .map_err(|e| e.to_string())?;

    let txn = db.begin().await.map_err(|e| e.to_string())?;

    let head = benchmark_suite::ActiveModel {
        id: Set(valid.id.clone()),
        name: Set(valid.name.clone()),
        description: Set(valid.description.clone()),
        mode: Set(valid.mode.clone()),
        warmup_runs: Set(valid.warmup_runs),
        repetitions: Set(valid.repetitions),
        // Saving is an edit, so the run counter starts again.
        run_count: Set(0),
        created_at: Set(existing.as_ref().map_or(now, |s| s.created_at)),
        updated_at: Set(now),
    };
    if existing.is_some() {
        head.update(&txn).await.map_err(|e| e.to_string())?;
    } else {
        head.insert(&txn).await.map_err(|e| e.to_string())?;
    }

    // Deleting the steps also deletes their file links (cascade); the steps are then re-added in order.
    benchmark_suite_step::Entity::delete_many()
        .filter(benchmark_suite_step::Column::SuiteId.eq(&valid.id))
        .exec(&txn)
        .await
        .map_err(|e| e.to_string())?;

    for (position, step) in valid.steps.iter().enumerate() {
        let prompt_known = benchmark_prompt::Entity::find_by_id(step.prompt_id.as_str())
            .one(&txn)
            .await
            .map_err(|e| e.to_string())?
            .is_some();
        if !prompt_known {
            return Err("A step uses a prompt that is no longer in the library.".to_string());
        }
        benchmark_suite_step::ActiveModel {
            id: Set(step.id.clone()),
            suite_id: Set(valid.id.clone()),
            position: Set(position as i32),
            prompt_id: Set(step.prompt_id.clone()),
        }
        .insert(&txn)
        .await
        .map_err(|e| e.to_string())?;

        for (file_position, file_id) in step.file_ids.iter().enumerate() {
            let file_known = benchmark_file::Entity::find_by_id(file_id.as_str())
                .one(&txn)
                .await
                .map_err(|e| e.to_string())?
                .is_some();
            if !file_known {
                return Err(
                    "A file is no longer in the library. Remove it and try again.".to_string(),
                );
            }
            benchmark_step_file::ActiveModel {
                step_id: Set(step.id.clone()),
                position: Set(file_position as i32),
                file_id: Set(file_id.clone()),
            }
            .insert(&txn)
            .await
            .map_err(|e| e.to_string())?;
        }
    }

    txn.commit().await.map_err(|e| e.to_string())?;

    let kept: HashSet<&String> = valid.steps.iter().flat_map(|s| s.file_ids.iter()).collect();
    let dropped: Vec<String> = previous_files
        .into_iter()
        .filter(|id| !kept.contains(id))
        .collect();
    remove_if_unreferenced(db, root, &dropped).await?;

    let saved = benchmark_suite::Entity::find_by_id(valid.id.as_str())
        .one(db)
        .await
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "suite was not saved".to_string())?;
    load_suite(db, saved).await
}

/// Delete a suite and its steps. Runs stay: their suite link is cleared, their record is kept.
async fn delete_suite(db: &DatabaseConnection, root: &Path, id: &str) -> Result<(), String> {
    let previous_files = step_file_ids_of_suite(db, id).await?;

    let result = benchmark_suite::Entity::delete_by_id(id)
        .exec(db)
        .await
        .map_err(|e| e.to_string())?;
    if result.rows_affected == 0 {
        return Err("This suite no longer exists.".to_string());
    }

    remove_if_unreferenced(db, root, &previous_files).await
}

fn validate(input: BenchmarkSuiteInput) -> Result<ValidSuite, String> {
    let id = input.id.trim().to_string();
    if id.is_empty() {
        return Err("A suite id is required.".to_string());
    }

    let name = input.name.trim().to_string();
    if name.is_empty() {
        return Err("Give the suite a name.".to_string());
    }
    if name.chars().count() > MAX_NAME_CHARS {
        return Err(format!("The name can be at most {MAX_NAME_CHARS} characters."));
    }

    let description = input
        .description
        .map(|d| d.trim().to_string())
        .filter(|d| !d.is_empty());
    if description
        .as_ref()
        .is_some_and(|d| d.chars().count() > MAX_DESCRIPTION_CHARS)
    {
        return Err(format!(
            "The description can be at most {MAX_DESCRIPTION_CHARS} characters."
        ));
    }

    let mode = input.mode;
    if mode != "conversation" && mode != "independent" {
        return Err("The mode must be 'conversation' or 'independent'.".to_string());
    }

    if !(0..=MAX_WARMUP_RUNS).contains(&input.warmup_runs) {
        return Err(format!(
            "Warmup runs must be between 0 and {MAX_WARMUP_RUNS}."
        ));
    }
    if !(1..=MAX_REPETITIONS).contains(&input.repetitions) {
        return Err(format!(
            "Repetitions must be between 1 and {MAX_REPETITIONS}."
        ));
    }

    if input.steps.is_empty() {
        return Err("A suite needs at least one step.".to_string());
    }
    if input.steps.len() > MAX_STEPS {
        return Err(format!("A suite can have at most {MAX_STEPS} steps."));
    }

    let mut step_ids: HashSet<String> = HashSet::new();
    let mut steps = Vec::with_capacity(input.steps.len());
    for raw in input.steps {
        let step_id = raw.id.trim().to_string();
        if step_id.is_empty() {
            return Err("Every step needs an id.".to_string());
        }
        if !step_ids.insert(step_id.clone()) {
            return Err("Two steps have the same id.".to_string());
        }
        let prompt_id = raw.prompt_id.trim().to_string();
        if prompt_id.is_empty() {
            return Err("Every step needs a prompt.".to_string());
        }
        let mut file_ids: Vec<String> = Vec::new();
        for file_id in raw.file_ids {
            if !file_ids.contains(&file_id) {
                file_ids.push(file_id);
            }
        }
        if file_ids.len() > MAX_FILES_PER_STEP {
            return Err(format!(
                "A step can have at most {MAX_FILES_PER_STEP} extra files."
            ));
        }
        steps.push(ValidStep {
            id: step_id,
            prompt_id,
            file_ids,
        });
    }

    Ok(ValidSuite {
        id,
        name,
        description,
        mode,
        warmup_runs: input.warmup_runs,
        repetitions: input.repetitions,
        steps,
    })
}

fn now_millis() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::super::benchmark_files::tests::TempStore;
    use super::super::benchmark_files::import_file;
    use super::super::benchmark_prompts::{delete_prompt, save_prompt};
    use super::*;
    use crate::commands::benchmark_prompts::BenchmarkPromptInput;
    use crate::entities::benchmark_run;


    fn prompt(id: &str, name: &str) -> BenchmarkPromptInput {
        BenchmarkPromptInput {
            id: id.into(),
            name: name.into(),
            description: None,
            text: format!("Tell me about {name}."),
            match_rule: "any".into(),
            keywords: vec![],
            file_ids: vec![],
        }
    }

    fn step(id: &str, prompt_id: &str, files: &[&str]) -> BenchmarkSuiteStepInput {
        BenchmarkSuiteStepInput {
            id: id.into(),
            prompt_id: prompt_id.into(),
            file_ids: files.iter().map(|s| s.to_string()).collect(),
        }
    }

    fn suite(id: &str, steps: Vec<BenchmarkSuiteStepInput>) -> BenchmarkSuiteInput {
        BenchmarkSuiteInput {
            id: id.into(),
            name: "Smoke".into(),
            description: None,
            mode: "conversation".into(),
            warmup_runs: 1,
            repetitions: 2,
            steps,
        }
    }

    #[tokio::test]
    async fn save_then_list_keeps_step_order_and_files() {
        let store = TempStore::new("suite-save");
        let db = store.db().await;
        save_prompt(&db, &store.root(), prompt("p1", "Capital")).await.expect("p1");
        save_prompt(&db, &store.root(), prompt("p2", "Summary")).await.expect("p2");
        let src = store.write("extra.txt", "abc");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");

        let saved = save_suite(
            &db,
            &store.root(),
            suite("s1", vec![step("st1", "p2", &[]), step("st2", "p1", &["f1"])]),
        )
        .await
        .expect("save");

        assert_eq!(saved.steps.len(), 2);
        assert_eq!(saved.steps[0].prompt_name, "Summary");
        assert_eq!(saved.steps[1].prompt_name, "Capital");
        assert_eq!(saved.steps[1].files[0].id, "f1");
        assert_eq!(saved.mode, "conversation");

        let listed = list_suites(&db).await.expect("list");
        assert_eq!(listed.len(), 1);
        assert_eq!(listed[0].steps[1].files[0].chars, Some(3));
    }

    #[tokio::test]
    async fn validation_rejects_bad_suites() {
        let store = TempStore::new("suite-validate");
        let db = store.db().await;
        save_prompt(&db, &store.root(), prompt("p1", "Capital")).await.expect("p1");

        let empty = suite("s1", vec![]);
        assert!(save_suite(&db, &store.root(), empty).await.is_err());

        let mut bad_mode = suite("s1", vec![step("st1", "p1", &[])]);
        bad_mode.mode = "parallel".into();
        assert!(validate(bad_mode).is_err());

        let mut too_many_warmups = suite("s1", vec![step("st1", "p1", &[])]);
        too_many_warmups.warmup_runs = MAX_WARMUP_RUNS + 1;
        assert!(validate(too_many_warmups).is_err());

        let mut zero_reps = suite("s1", vec![step("st1", "p1", &[])]);
        zero_reps.repetitions = 0;
        assert!(validate(zero_reps).is_err());

        let unknown_prompt = suite("s1", vec![step("st1", "nope", &[])]);
        assert!(save_suite(&db, &store.root(), unknown_prompt).await.is_err());

        let duplicate_step = suite("s1", vec![step("st1", "p1", &[]), step("st1", "p1", &[])]);
        assert!(validate(duplicate_step).is_err());
    }

    #[tokio::test]
    async fn removing_a_step_removes_its_file() {
        let store = TempStore::new("suite-drop-step");
        let db = store.db().await;
        save_prompt(&db, &store.root(), prompt("p1", "Capital")).await.expect("p1");
        let src = store.write("extra.txt", "abc");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");
        save_suite(&db, &store.root(), suite("s1", vec![step("st1", "p1", &["f1"])]))
            .await
            .expect("save with file");

        save_suite(&db, &store.root(), suite("s1", vec![step("st1", "p1", &[])]))
            .await
            .expect("save without file");

        assert!(!store.root().join("f1").exists());
    }

    #[tokio::test]
    async fn deleting_a_suite_removes_its_files_and_keeps_its_runs() {
        let store = TempStore::new("suite-delete");
        let db = store.db().await;
        save_prompt(&db, &store.root(), prompt("p1", "Capital")).await.expect("p1");
        let src = store.write("extra.txt", "abc");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");
        save_suite(&db, &store.root(), suite("s1", vec![step("st1", "p1", &["f1"])]))
            .await
            .expect("save");
        benchmark_run::ActiveModel {
            id: Set("r1".into()),
            suite_id: Set(Some("s1".into())),
            suite_name: Set("Smoke".into()),
            model_name: Set("org/model".into()),
            model_key: Set("org/model".into()),
            compute: Set("npu".into()),
            mode: Set("conversation".into()),
            warmup_runs: Set(1),
            repetitions: Set(2),
            status: Set("completed".into()),
            started_at: Set(1),
            ..Default::default()
        }
        .insert(&db)
        .await
        .expect("run");

        delete_suite(&db, &store.root(), "s1").await.expect("delete");

        assert!(list_suites(&db).await.expect("list").is_empty());
        assert!(!store.root().join("f1").exists());
        let run = benchmark_run::Entity::find_by_id("r1")
            .one(&db)
            .await
            .expect("query")
            .expect("run kept");
        assert_eq!(run.suite_id, None);
        assert_eq!(run.suite_name, "Smoke");
    }

    #[tokio::test]
    async fn a_prompt_in_a_suite_still_cannot_be_deleted() {
        let store = TempStore::new("suite-prompt-guard");
        let db = store.db().await;
        save_prompt(&db, &store.root(), prompt("p1", "Capital")).await.expect("p1");
        save_suite(&db, &store.root(), suite("s1", vec![step("st1", "p1", &[])]))
            .await
            .expect("save");

        let err = delete_prompt(&db, &store.root(), "p1").await.expect_err("in use");
        assert!(err.contains("Smoke"), "names the suite: {err}");
        assert_eq!(list_suites(&db).await.expect("list").len(), 1);
    }
}
