const EVENT_PROGRESS: &str = "benchmark-progress";
const EVENT_FINISHED: &str = "benchmark-finished";
/// How often a waiting request checks whether the user cancelled.
const CANCEL_POLL: Duration = Duration::from_millis(200);
/// Longest one prompt may take before it is recorded as failed.
const STEP_TIMEOUT: Duration = Duration::from_secs(600);
const MAX_TEMPERATURE: f64 = 2.0;
const MAX_TOKENS_LIMIT: u32 = 8192;

/// The run in progress. Only one run executes at a time; chat and model changes wait for it.
#[derive(Default)]
pub struct BenchmarkRunState {
    active: Mutex<Option<ActiveRun>>,
}

struct ActiveRun {
    run_id: String,
    cancel: Arc<AtomicBool>,
}

impl BenchmarkRunState {
    /// Id of the run in progress, if any.
    pub fn active_run_id(&self) -> Option<String> {
        self.active
            .lock()
            .ok()
            .and_then(|guard| guard.as_ref().map(|run| run.run_id.clone()))
    }

    fn begin(&self, run_id: &str) -> Result<Arc<AtomicBool>, String> {
        let mut guard = self
            .active
            .lock()
            .map_err(|_| "benchmark state is unavailable".to_string())?;
        if guard.is_some() {
            return Err("A benchmark run is already in progress.".to_string());
        }
        let cancel = Arc::new(AtomicBool::new(false));
        *guard = Some(ActiveRun {
            run_id: run_id.to_string(),
            cancel: cancel.clone(),
        });
        Ok(cancel)
    }

    fn end(&self) {
        if let Ok(mut guard) = self.active.lock() {
            *guard = None;
        }
    }

    fn request_cancel(&self, run_id: &str) -> Result<(), String> {
        let guard = self
            .active
            .lock()
            .map_err(|_| "benchmark state is unavailable".to_string())?;
        match guard.as_ref() {
            Some(run) if run.run_id == run_id => {
                run.cancel.store(true, Ordering::SeqCst);
                Ok(())
            }
            _ => Err("That run is not in progress.".to_string()),
        }
    }
}

/// Refuse work that would disturb a run in progress: chat and model loads or unloads.
pub fn ensure_no_active_run(state: &BenchmarkRunState) -> Result<(), String> {
    match state.active_run_id() {
        Some(_) => Err(
            "A benchmark run is in progress. Chat and model changes wait until it finishes."
                .to_string(),
        ),
        None => Ok(()),
    }
}

/// What the Run panel sends. `runId` is generated by the frontend so it can follow the events.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StartRunRequest {
    pub run_id: String,
    pub suite_id: String,
    pub model_name: String,
    /// `npu`, `gpu` or `cpu`.
    pub compute: String,
    pub port: u16,
    pub temperature: f64,
    pub top_p: f64,
    pub max_tokens: u32,
    /// The model's load parameters, with the compute target. Sent with every request, as chat does; without
    /// them the server keeps the model it has, whatever compute was chosen.
    pub load: Option<ModelLoadParams>,
}

/// Progress for one step. `state` is `started`, `completed`, `failed` or `skipped`.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct ProgressEvent {
    run_id: String,
    pass: i32,
    total_passes: i32,
    step_index: i32,
    total_steps: i32,
    prompt_name: String,
    is_warmup: bool,
    state: &'static str,
    ttft_ms: Option<f64>,
    total_ms: Option<i64>,
    tokens_per_sec: Option<f64>,
    passed: Option<bool>,
    error: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct FinishedEvent {
    run_id: String,
    status: String,
    error: Option<String>,
}

/// Where a step sits in the run: which pass and which position.
#[derive(Debug, Clone, Copy)]
struct Cursor {
    pass: i32,
    total_passes: i32,
    index: i32,
    total_steps: i32,
    is_warmup: bool,
}

/// The suite as the runner needs it, read once when the run starts.
#[derive(Debug, Clone)]
struct Plan {
    suite_id: String,
    suite_name: String,
    mode: String,
    warmup_runs: i32,
    repetitions: i32,
    steps: Vec<PlanStep>,
    /// Each prompt once, for the run counter.
    prompt_ids: Vec<String>,
}

#[derive(Debug, Clone)]
struct PlanStep {
    prompt_name: String,
    prompt_text: String,
    keywords: Vec<String>,
    match_rule: String,
    /// The prompt's files, then the step's extra files.
    attachments: Vec<AttachmentFile>,
    /// Snapshots of the same files, kept with the run.
    files: Vec<FileRecord>,
}

#[derive(Debug, Clone)]
struct FileRecord {
    name: String,
    kind: String,
    size: Option<i64>,
    sha256: String,
}

/// Outcome of the whole run, written to the run row and the finished event.
struct RunResult {
    status: &'static str,
    error: Option<String>,
    total_memory: Option<u64>,
}

#[tauri::command]
pub async fn start_benchmark_run(
    app: AppHandle,
    db: State<'_, DatabaseConnection>,
    request: StartRunRequest,
) -> Result<(), String> {
    validate_request(&request)?;
    eprintln!(
        "[benchmark] run {} requested: suite {}, model {}, compute {}",
        request.run_id, request.suite_id, request.model_name, request.compute
    );
    let run_state = app.state::<BenchmarkRunState>();
    let cancel = run_state.begin(&request.run_id)?;
    let db: DatabaseConnection = (*db).clone();

    let (plan, server_model) = match prepare(&app, &db, &request).await {
        Ok(prepared) => prepared,
        Err(e) => {
            eprintln!("[benchmark] run {} did not start: {e}", request.run_id);
            run_state.end();
            return Err(e);
        }
    };

    // The run uses the id the server reports for the model, which is the one it accepts.
    let request = StartRunRequest {
        model_name: server_model,
        ..request
    };
    let task_app = app.clone();
    tauri::async_runtime::spawn(async move {
        let result = execute(&task_app, &db, &request, &plan, &cancel).await;
        eprintln!("[benchmark] run {} ended: {}", request.run_id, result.status);
        if let Err(e) = finish_run(&db, &request.run_id, &plan, &result).await {
            eprintln!("[benchmark] could not save the run result: {e}");
        }
        task_app.state::<BenchmarkRunState>().end();
        let _ = task_app.emit(
            EVENT_FINISHED,
            FinishedEvent {
                run_id: request.run_id.clone(),
                status: result.status.to_string(),
                error: result.error.clone(),
            },
        );
    });
    Ok(())
}

/// Stop the run after the request in flight. The steps already finished are kept.
#[tauri::command]
pub fn cancel_benchmark_run(
    run_state: State<'_, BenchmarkRunState>,
    run_id: String,
) -> Result<(), String> {
    run_state.request_cancel(&run_id)
}

fn validate_request(request: &StartRunRequest) -> Result<(), String> {
    if request.run_id.trim().is_empty() || request.suite_id.trim().is_empty() {
        return Err("A run needs a suite and an id.".to_string());
    }
    if request.model_name.trim().is_empty() {
        return Err("Load a model before starting a run.".to_string());
    }
    if !matches!(request.compute.as_str(), "npu" | "gpu" | "cpu") {
        return Err("The compute target must be npu, gpu or cpu.".to_string());
    }
    if !(0.0..=MAX_TEMPERATURE).contains(&request.temperature) {
        return Err(format!("Temperature must be between 0 and {MAX_TEMPERATURE}."));
    }
    if !(0.0..=1.0).contains(&request.top_p) {
        return Err("Top-p must be between 0 and 1.".to_string());
    }
    if request.max_tokens == 0 || request.max_tokens > MAX_TOKENS_LIMIT {
        return Err(format!(
            "Max tokens must be between 1 and {MAX_TOKENS_LIMIT}."
        ));
    }
    Ok(())
}

/// Checks the server has the model loaded, reads the suite and writes the run row.
/// Finds the requested model among those the server has loaded. Returns the plan and the server's
/// id for the model.
async fn prepare(
    app: &AppHandle,
    db: &DatabaseConnection,
    request: &StartRunRequest,
) -> Result<(Plan, String), String> {
    let client = app.state::<AppState>().http_client.clone();
    let base = format!("http://127.0.0.1:{}", request.port);
    let loaded = fetch_loaded_models(&client, &base)
        .await
        .map_err(|_| "The GenieX server is not responding. Start it and load the model first.".to_string())?;
    let server_model = loaded
        .iter()
        .find(|m| same_model(m, &request.model_name))
        .cloned()
        .ok_or_else(|| {
            let has = if loaded.is_empty() {
                "nothing".to_string()
            } else {
                loaded.join(", ")
            };
            format!(
                "The model {} is not loaded on the server. The server has: {has}.",
                request.model_name
            )
        })?;

    let plan = build_plan(db, &request.suite_id).await?;
    eprintln!(
        "[benchmark] run {}: {} steps, {} warmup and {} timed passes",
        request.run_id,
        plan.steps.len(),
        plan.warmup_runs,
        plan.repetitions
    );
    let stored = StartRunRequest {
        model_name: server_model.clone(),
        ..request.clone()
    };
    let power = tokio::task::spawn_blocking(super::power::read_power_state)
        .await
        .unwrap_or_default();
    create_run_row(db, &stored, &plan, &power).await?;
    Ok((plan, server_model))
}

/// True when two names are the same model: equal once the precision suffix is removed, or with the
/// same repository name under another org.
fn same_model(loaded: &str, wanted: &str) -> bool {
    let a = strip_precision(loaded);
    let b = strip_precision(wanted);
    a == b || short_name(a) == short_name(b)
}

/// The repository name without its org: "unsloth/Qwen3.5-0.8B-GGUF" -> "Qwen3.5-0.8B-GGUF".
fn short_name(name: &str) -> &str {
    name.rsplit('/').next().unwrap_or(name)
}

async fn build_plan(db: &DatabaseConnection, suite_id: &str) -> Result<Plan, String> {
    let suite = benchmark_suite::Entity::find_by_id(suite_id)
        .one(db)
        .await
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "This suite no longer exists.".to_string())?;
    let step_rows = benchmark_suite_step::Entity::find()
        .filter(benchmark_suite_step::Column::SuiteId.eq(suite_id))
        .order_by_asc(benchmark_suite_step::Column::Position)
        .all(db)
        .await
        .map_err(|e| e.to_string())?;

    let mut steps = Vec::with_capacity(step_rows.len());
    let mut prompt_ids: Vec<String> = Vec::new();
    for row in step_rows {
        let prompt = benchmark_prompt::Entity::find_by_id(row.prompt_id.as_str())
            .one(db)
            .await
            .map_err(|e| e.to_string())?
            .ok_or_else(|| "A prompt in this suite is no longer in the library.".to_string())?;
        let keywords: Vec<String> = benchmark_prompt_keyword::Entity::find()
            .filter(benchmark_prompt_keyword::Column::PromptId.eq(&prompt.id))
            .order_by_asc(benchmark_prompt_keyword::Column::Position)
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|k| k.keyword)
            .collect();
        let prompt_file_ids: Vec<String> = benchmark_prompt_file::Entity::find()
            .filter(benchmark_prompt_file::Column::PromptId.eq(&prompt.id))
            .order_by_asc(benchmark_prompt_file::Column::Position)
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|l| l.file_id)
            .collect();
        let step_file_ids: Vec<String> = benchmark_step_file::Entity::find()
            .filter(benchmark_step_file::Column::StepId.eq(&row.id))
            .order_by_asc(benchmark_step_file::Column::Position)
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|l| l.file_id)
            .collect();

        let mut attachments = Vec::new();
        let mut files = Vec::new();
        for id in prompt_file_ids.iter().chain(step_file_ids.iter()) {
            let file = benchmark_file::Entity::find_by_id(id.as_str())
                .one(db)
                .await
                .map_err(|e| e.to_string())?
                .ok_or_else(|| "A file in this suite is no longer in the library.".to_string())?;
            let attachment = read_attachment_file(Path::new(&file.stored_path))
                .map_err(|e| format!("{}: {e}", file.name))?;
            files.push(FileRecord {
                name: file.name,
                kind: file.kind,
                size: file.size,
                sha256: file.sha256,
            });
            attachments.push(attachment);
        }

        if !prompt_ids.contains(&prompt.id) {
            prompt_ids.push(prompt.id.clone());
        }
        steps.push(PlanStep {
            prompt_name: prompt.name,
            prompt_text: prompt.text,
            keywords,
            match_rule: prompt.match_rule,
            attachments,
            files,
        });
    }

    Ok(Plan {
        suite_id: suite.id,
        suite_name: suite.name,
        mode: suite.mode,
        warmup_runs: suite.warmup_runs,
        repetitions: suite.repetitions,
        steps,
        prompt_ids,
    })
}

async fn create_run_row(
    db: &DatabaseConnection,
    request: &StartRunRequest,
    plan: &Plan,
    power: &super::power::PowerState,
) -> Result<(), String> {
    benchmark_run::ActiveModel {
        id: Set(request.run_id.clone()),
        suite_id: Set(Some(plan.suite_id.clone())),
        suite_name: Set(plan.suite_name.clone()),
        model_name: Set(request.model_name.clone()),
        model_key: Set(strip_precision(&request.model_name).to_string()),
        compute: Set(request.compute.clone()),
        precision: Set(None),
        nctx: Set(None),
        ngl: Set(None),
        // The GenieX power mode the model was loaded with, when one was set.
        power_mode: Set(request.load.as_ref().and_then(|l| l.power_mode.clone()).filter(|m| !m.is_empty())),
        windows_power_plan: Set(power.windows_power_plan.clone()),
        on_battery: Set(power.on_battery),
        temperature: Set(Some(request.temperature)),
        top_p: Set(Some(request.top_p)),
        seed: Set(None),
        max_tokens: Set(Some(i64::from(request.max_tokens))),
        mode: Set(plan.mode.clone()),
        warmup_runs: Set(plan.warmup_runs),
        repetitions: Set(plan.repetitions),
        geniex_version: Set(None),
        chipset: Set(None),
        total_memory_bytes: Set(None),
        status: Set("running".to_string()),
        error: Set(None),
        started_at: Set(now_millis()),
        finished_at: Set(None),
    }
    .insert(db)
    .await
    .map(|_| ())
    .map_err(|e| e.to_string())
}

/// Runs every pass: warmup passes first (not counted), then the timed repetitions. Each pass goes
/// through the steps in order. Conversation mode carries the history from one step to the next
/// within a pass; a failed step stops the run there and the rest are recorded as skipped.
async fn execute(
    app: &AppHandle,
    db: &DatabaseConnection,
    request: &StartRunRequest,
    plan: &Plan,
    cancel: &AtomicBool,
) -> RunResult {
    let client = app.state::<AppState>().http_client.clone();
    let pid = app
        .state::<AppState>()
        .server_process
        .lock()
        .ok()
        .and_then(|guard| *guard);
    let url = format!("http://127.0.0.1:{}/v1/chat/completions", request.port);
    let settings = match settings_for(request) {
        Ok(settings) => settings,
        Err(e) => {
            return RunResult {
                status: "failed",
                error: Some(e),
                total_memory: None,
            }
        }
    };
    let conversation = plan.mode == "conversation";
    let total_passes = plan.warmup_runs + plan.repetitions;
    let total_steps = plan.steps.len() as i32;

    let mut status = "completed";
    let mut error: Option<String> = None;
    let mut stop_rest = false;
    let mut total_memory = None;

    'passes: for pass in 0..total_passes {
        let mut history: Vec<Value> = Vec::new();
        for (index, step) in plan.steps.iter().enumerate() {
            let cursor = Cursor {
                pass,
                total_passes,
                index: index as i32,
                total_steps,
                is_warmup: pass < plan.warmup_runs,
            };
            if cancel.load(Ordering::SeqCst) {
                status = "cancelled";
                break 'passes;
            }
            if stop_rest {
                save_step(db, &request.run_id, cursor, step, StepRow::skipped()).await;
                emit(app, &request.run_id, cursor, step, "skipped", None);
                continue;
            }

            eprintln!(
                "[benchmark] run {}: pass {} step {} ({})",
                request.run_id,
                pass + 1,
                index + 1,
                step.prompt_name
            );
            emit(app, &request.run_id, cursor, step, "started", None);
            let user = user_message(step);
            let messages = if conversation {
                let mut messages = history.clone();
                messages.push(user.clone());
                messages
            } else {
                vec![user.clone()]
            };
            // The server takes the model without its precision suffix, as chat sends it.
            let model = strip_precision(&request.model_name).to_string();
            let body = build_chat_body(messages, Some(model), &settings);

            let sampler = Sampler::start(pid, request.port);
            let outcome = run_request(&client, &url, &body, cancel).await;
            let samples = sampler.finish().await;
            let resources = summarize(&samples);
            if resources.total_memory.is_some() {
                total_memory = resources.total_memory;
            }

            match outcome {
                Err(StepError::Cancelled) => {
                    status = "cancelled";
                    break 'passes;
                }
                Err(StepError::Failed(message)) => {
                    eprintln!("[benchmark] run {}: step failed: {message}", request.run_id);
                    save_step(
                        db,
                        &request.run_id,
                        cursor,
                        step,
                        StepRow::failed(&message, &resources),
                    )
                    .await;
                    emit(app, &request.run_id, cursor, step, "failed", Some(message.clone()));
                    if conversation {
                        stop_rest = true;
                        status = "failed";
                        error = Some(message);
                    }
                }
                Ok(output) => {
                    let keyword = evaluate_keywords(&output.output, &step.keywords, &step.match_rule);
                    save_step(
                        db,
                        &request.run_id,
                        cursor,
                        step,
                        StepRow::completed(output.clone(), &resources, keyword),
                    )
                    .await;
                    emit_finished_step(app, &request.run_id, cursor, step, &output, keyword.passed);
                    if conversation {
                        history.push(user);
                        history.push(json!({ "role": "assistant", "content": output.output }));
                    }
                }
            }
        }
    }

    RunResult {
        status,
        error,
        total_memory,
    }
}

/// Saves the outcome and, for a completed run, adds one to the suite's and each prompt's counter.
async fn finish_run(
    db: &DatabaseConnection,
    run_id: &str,
    plan: &Plan,
    result: &RunResult,
) -> Result<(), String> {
    let txn = db.begin().await.map_err(|e| e.to_string())?;
    let run = benchmark_run::Entity::find_by_id(run_id)
        .one(&txn)
        .await
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "the run row is missing".to_string())?;
    let mut run = benchmark_run::ActiveModel::from(run);
    run.status = Set(result.status.to_string());
    run.error = Set(result.error.clone());
    run.finished_at = Set(Some(now_millis()));
    run.total_memory_bytes = Set(result.total_memory.map(|v| v as i64));
    run.update(&txn).await.map_err(|e| e.to_string())?;

    if result.status == "completed" {
        if let Some(suite) = benchmark_suite::Entity::find_by_id(plan.suite_id.as_str())
            .one(&txn)
            .await
            .map_err(|e| e.to_string())?
        {
            let next = suite.run_count + 1;
            let mut suite = benchmark_suite::ActiveModel::from(suite);
            suite.run_count = Set(next);
            suite.update(&txn).await.map_err(|e| e.to_string())?;
        }
        for prompt_id in &plan.prompt_ids {
            if let Some(prompt) = benchmark_prompt::Entity::find_by_id(prompt_id.as_str())
                .one(&txn)
                .await
                .map_err(|e| e.to_string())?
            {
                let next = prompt.run_count + 1;
                let mut prompt = benchmark_prompt::ActiveModel::from(prompt);
                prompt.run_count = Set(next);
                prompt.update(&txn).await.map_err(|e| e.to_string())?;
            }
        }
    }

    txn.commit().await.map_err(|e| e.to_string())
}

/// The message for one step: the prompt text, then its files. Text files are inlined with the
/// same `--- file: name ---` header the system prompt uses; images and audio become content parts.
fn user_message(step: &PlanStep) -> Value {
    let mut text = step.prompt_text.clone();
    let mut media: Vec<Value> = Vec::new();
    for file in &step.attachments {
        match file.kind {
            AttachmentKind::Text => {
                if let Some(content) = &file.text {
                    text.push_str(&format!("\n\n--- file: {} ---\n{}", file.name, content));
                }
            }
            AttachmentKind::Image => {
                if let (Some(data), Some(mime)) = (&file.data, &file.mime) {
                    media.push(json!({
                        "type": "image_url",
                        "image_url": { "url": format!("data:{mime};base64,{data}") }
                    }));
                }
            }
            AttachmentKind::Audio => {
                if let Some(data) = &file.data {
                    let format = if file.mime.as_deref() == Some("audio/wav") {
                        "wav"
                    } else {
                        "mp3"
                    };
                    media.push(json!({
                        "type": "input_audio",
                        "input_audio": { "data": data, "format": format }
                    }));
                }
            }
        }
    }
    if media.is_empty() {
        return json!({ "role": "user", "content": text });
    }
    let mut parts = vec![json!({ "type": "text", "text": text })];
    parts.extend(media);
    json!({ "role": "user", "content": parts })
}

fn settings_for(request: &StartRunRequest) -> Result<GenerationSettings, String> {
    let mut value = match &request.load {
        Some(load) => serde_json::to_value(load).map_err(|e| format!("invalid load settings: {e}"))?,
        None => json!({}),
    };
    let fields = value
        .as_object_mut()
        .ok_or_else(|| "load settings must be an object".to_string())?;
    fields.insert("temperature".into(), json!(request.temperature));
    fields.insert("topP".into(), json!(request.top_p));
    fields.insert("maxTokens".into(), json!(request.max_tokens));
    serde_json::from_value(value).map_err(|e| format!("invalid generation settings: {e}"))
}

enum StepError {
    Cancelled,
    Failed(String),
}

/// What one streamed request measured.
#[derive(Debug, Clone)]
struct StepOutput {
    output: String,
    ttft_ms: Option<f64>,
    total_ms: i64,
    prompt_tokens: Option<i64>,
    completion_tokens: Option<i64>,
    tokens_per_sec: Option<f64>,
}

/// One streamed chat request. Timing starts when the request is sent. Stops on the cancel flag.
async fn run_request(
    client: &reqwest::Client,
    url: &str,
    body: &Value,
    cancel: &AtomicBool,
) -> Result<StepOutput, StepError> {
    let started = Instant::now();
    let mut response = client
        .post(url)
        .timeout(STEP_TIMEOUT)
        .json(body)
        .send()
        .await
        .map_err(|e| StepError::Failed(format!("request failed: {e}")))?;
    if !response.status().is_success() {
        return Err(StepError::Failed(format!(
            "the server returned {}",
            response.status()
        )));
    }

    let mut reader = StreamReader::new(started);
    loop {
        if cancel.load(Ordering::SeqCst) {
            return Err(StepError::Cancelled);
        }
        match tokio::time::timeout(CANCEL_POLL, response.chunk()).await {
            Err(_) => continue,
            Ok(Err(e)) => return Err(StepError::Failed(format!("stream failed: {e}"))),
            Ok(Ok(None)) => break,
            Ok(Ok(Some(bytes))) => reader.push(&bytes),
        }
    }
    Ok(reader.finish())
}

/// Reads the server-sent events of one reply: the text, the time to the first token, and the exact
/// token counts from the usage chunk.
struct StreamReader {
    pending: Vec<u8>,
    output: String,
    usage: Option<crate::commands::chat_helpers::ReplyUsage>,
    chunks: i64,
    first_token_ms: Option<f64>,
    started: Instant,
}

impl StreamReader {
    fn new(started: Instant) -> Self {
        Self {
            pending: Vec::new(),
            output: String::new(),
            usage: None,
            chunks: 0,
            first_token_ms: None,
            started,
        }
    }

    fn push(&mut self, bytes: &[u8]) {
        self.pending.extend_from_slice(bytes);
        while let Some(pos) = self.pending.iter().position(|b| *b == b'\n') {
            let line: Vec<u8> = self.pending.drain(..=pos).collect();
            self.line(&line);
        }
    }

    fn line(&mut self, raw: &[u8]) {
        let text = String::from_utf8_lossy(raw);
        let Some(data) = text.trim().strip_prefix("data:") else {
            return;
        };
        let data = data.trim();
        if data.is_empty() || data == "[DONE]" {
            return;
        }
        let Ok(value) = serde_json::from_str::<Value>(data) else {
            return;
        };
        if let Some(usage) = usage_from_chunk(&value) {
            self.usage = Some(usage);
        }
        if let Some(content) = value["choices"][0]["delta"]["content"]
            .as_str()
            .filter(|c| !c.is_empty())
        {
            if self.first_token_ms.is_none() {
                self.first_token_ms = Some(self.started.elapsed().as_secs_f64() * 1000.0);
            }
            self.output.push_str(content);
            self.chunks += 1;
        }
    }

    fn finish(mut self) -> StepOutput {
        let rest = std::mem::take(&mut self.pending);
        self.line(&rest);
        let total_ms = self.started.elapsed().as_millis() as i64;
        let completion_tokens = self.usage.map(|u| u.completion_tokens as i64);
        // Without a usage chunk (a stream the server cut short) count the text chunks instead.
        let tokens = completion_tokens.unwrap_or(self.chunks);
        let tokens_per_sec = (total_ms > 0 && tokens > 0)
            .then(|| tokens as f64 / (total_ms as f64 / 1000.0));
        StepOutput {
            output: self.output,
            ttft_ms: self.first_token_ms,
            total_ms,
            prompt_tokens: self.usage.map(|u| u.prompt_tokens as i64),
            completion_tokens,
            tokens_per_sec,
        }
    }
}

/// Samples CPU, GPU, NPU and memory every second while a step runs.
struct Sampler {
    stop: Arc<AtomicBool>,
    task: tokio::task::JoinHandle<Vec<SystemUsage>>,
}

impl Sampler {
    fn start(pid: Option<u32>, port: u16) -> Self {
        let stop = Arc::new(AtomicBool::new(false));
        let flag = stop.clone();
        let task = tokio::spawn(async move {
            let mut samples = Vec::new();
            while !flag.load(Ordering::SeqCst) {
                match tokio::task::spawn_blocking(move || sample_usage(pid, port)).await {
                    Ok(sample) => samples.push(sample),
                    Err(_) => break,
                }
            }
            samples
        });
        Self { stop, task }
    }

    /// Stops sampling and returns what was collected. A sample in progress finishes first.
    async fn finish(self) -> Vec<SystemUsage> {
        self.stop.store(true, Ordering::SeqCst);
        self.task.await.unwrap_or_default()
    }
}

/// Summary of one step's samples. Model memory is the server process tree.
#[derive(Debug, Clone, Default, PartialEq)]
struct ResourceSummary {
    peak_model_memory: Option<i64>,
    avg_model_memory: Option<i64>,
    peak_memory_used: Option<i64>,
    avg_cpu: Option<f64>,
    avg_gpu: Option<f64>,
    avg_npu: Option<f64>,
    total_memory: Option<u64>,
}

fn summarize(samples: &[SystemUsage]) -> ResourceSummary {
    if samples.is_empty() {
        return ResourceSummary::default();
    }
    let model: Vec<u64> = samples.iter().filter_map(|s| s.model_memory_bytes).collect();
    let (peak_model_memory, avg_model_memory) = if model.is_empty() {
        (None, None)
    } else {
        let peak = model.iter().copied().max().unwrap_or(0);
        let avg = model.iter().sum::<u64>() / model.len() as u64;
        (Some(peak as i64), Some(avg as i64))
    };
    ResourceSummary {
        peak_model_memory,
        avg_model_memory,
        peak_memory_used: samples
            .iter()
            .map(|s| s.memory_used_bytes)
            .max()
            .map(|v| v as i64),
        avg_cpu: mean(samples.iter().map(|s| s.cpu)),
        avg_gpu: mean(samples.iter().filter_map(|s| s.gpu)),
        avg_npu: mean(samples.iter().filter_map(|s| s.npu)),
        total_memory: samples.last().map(|s| s.memory_total_bytes),
    }
}

fn mean(values: impl Iterator<Item = f64>) -> Option<f64> {
    let values: Vec<f64> = values.collect();
    if values.is_empty() {
        return None;
    }
    Some(values.iter().sum::<f64>() / values.len() as f64)
}

/// Keyword result for one reply. All fields are None when the prompt has no keywords.
#[derive(Debug, Clone, Copy, PartialEq)]
struct KeywordResult {
    passed: Option<bool>,
    matched: Option<i32>,
    expected: Option<i32>,
}

/// Checks the reply against the keywords: whole words, ignoring case. `all` needs every keyword,
/// `any` needs one.
fn evaluate_keywords(output: &str, keywords: &[String], rule: &str) -> KeywordResult {
    if keywords.is_empty() {
        return KeywordResult {
            passed: None,
            matched: None,
            expected: None,
        };
    }
    let haystack = output.to_lowercase();
    let matched = keywords
        .iter()
        .filter(|k| contains_word(&haystack, &k.to_lowercase()))
        .count();
    let expected = keywords.len();
    let passed = if rule == "all" {
        matched == expected
    } else {
        matched > 0
    };
    KeywordResult {
        passed: Some(passed),
        matched: Some(matched as i32),
        expected: Some(expected as i32),
    }
}

/// True when `needle` appears in `haystack` with no letter or digit on either side.
fn contains_word(haystack: &str, needle: &str) -> bool {
    if needle.is_empty() {
        return false;
    }
    let mut start = 0;
    while let Some(offset) = haystack[start..].find(needle) {
        let at = start + offset;
        let end = at + needle.len();
        let before_ok = haystack[..at]
            .chars()
            .next_back()
            .is_none_or(|c| !c.is_alphanumeric());
        let after_ok = haystack[end..]
            .chars()
            .next()
            .is_none_or(|c| !c.is_alphanumeric());
        if before_ok && after_ok {
            return true;
        }
        start = at + needle.chars().next().map_or(1, char::len_utf8);
    }
    false
}

/// What a step row stores. Built by the constructors below; a skipped step has no measurements.
struct StepRow {
    status: &'static str,
    output: Option<String>,
    timing: Option<StepOutput>,
    resources: ResourceSummary,
    keyword: Option<KeywordResult>,
    error: Option<String>,
}

impl StepRow {
    fn completed(output: StepOutput, resources: &ResourceSummary, keyword: KeywordResult) -> Self {
        Self {
            status: "completed",
            output: Some(output.output.clone()),
            timing: Some(output),
            resources: resources.clone(),
            keyword: Some(keyword),
            error: None,
        }
    }

    fn failed(message: &str, resources: &ResourceSummary) -> Self {
        Self {
            status: "failed",
            output: None,
            timing: None,
            resources: resources.clone(),
            keyword: None,
            error: Some(message.to_string()),
        }
    }

    fn skipped() -> Self {
        Self {
            status: "skipped",
            output: None,
            timing: None,
            resources: ResourceSummary::default(),
            keyword: None,
            error: None,
        }
    }
}

/// Writes one step and its file snapshots. A database error is logged, not fatal: the run goes on.
async fn save_step(
    db: &DatabaseConnection,
    run_id: &str,
    cursor: Cursor,
    step: &PlanStep,
    row: StepRow,
) {
    let id = format!("{run_id}-{}-{}", cursor.pass, cursor.index);
    let timing = row.timing.as_ref();
    let keyword = row.keyword.unwrap_or(KeywordResult {
        passed: None,
        matched: None,
        expected: None,
    });
    let result = benchmark_run_step::ActiveModel {
        id: Set(id.clone()),
        run_id: Set(run_id.to_string()),
        position: Set(cursor.index),
        repetition_index: Set(cursor.pass),
        is_warmup: Set(cursor.is_warmup),
        prompt_name: Set(step.prompt_name.clone()),
        prompt_text: Set(step.prompt_text.clone()),
        output_text: Set(row.output.clone()),
        ttft_ms: Set(timing.and_then(|t| t.ttft_ms)),
        total_ms: Set(timing.map(|t| t.total_ms)),
        tokens_per_sec: Set(timing.and_then(|t| t.tokens_per_sec)),
        prompt_tokens: Set(timing.and_then(|t| t.prompt_tokens)),
        completion_tokens: Set(timing.and_then(|t| t.completion_tokens)),
        peak_model_memory_bytes: Set(row.resources.peak_model_memory),
        avg_model_memory_bytes: Set(row.resources.avg_model_memory),
        peak_memory_used_bytes: Set(row.resources.peak_memory_used),
        avg_cpu: Set(row.resources.avg_cpu),
        avg_gpu: Set(row.resources.avg_gpu),
        avg_npu: Set(row.resources.avg_npu),
        passed: Set(keyword.passed),
        matched_keywords: Set(keyword.matched),
        expected_keywords: Set(keyword.expected),
        status: Set(row.status.to_string()),
        error: Set(row.error.clone()),
    }
    .insert(db)
    .await;
    if let Err(e) = result {
        eprintln!("[benchmark] could not save step {id}: {e}");
        return;
    }

    for (position, file) in step.files.iter().enumerate() {
        let saved = benchmark_run_step_file::ActiveModel {
            run_step_id: Set(id.clone()),
            position: Set(position as i32),
            name: Set(file.name.clone()),
            kind: Set(file.kind.clone()),
            size: Set(file.size),
            sha256: Set(file.sha256.clone()),
        }
        .insert(db)
        .await;
        if let Err(e) = saved {
            eprintln!("[benchmark] could not save file {} of {id}: {e}", file.name);
        }
    }
}

fn emit(
    app: &AppHandle,
    run_id: &str,
    cursor: Cursor,
    step: &PlanStep,
    state: &'static str,
    error: Option<String>,
) {
    emit_event(
        app,
        ProgressEvent {
            run_id: run_id.to_string(),
            pass: cursor.pass,
            total_passes: cursor.total_passes,
            step_index: cursor.index,
            total_steps: cursor.total_steps,
            prompt_name: step.prompt_name.clone(),
            is_warmup: cursor.is_warmup,
            state,
            ttft_ms: None,
            total_ms: None,
            tokens_per_sec: None,
            passed: None,
            error,
        },
    );
}

fn emit_finished_step(
    app: &AppHandle,
    run_id: &str,
    cursor: Cursor,
    step: &PlanStep,
    output: &StepOutput,
    passed: Option<bool>,
) {
    emit_event(
        app,
        ProgressEvent {
            run_id: run_id.to_string(),
            pass: cursor.pass,
            total_passes: cursor.total_passes,
            step_index: cursor.index,
            total_steps: cursor.total_steps,
            prompt_name: step.prompt_name.clone(),
            is_warmup: cursor.is_warmup,
            state: "completed",
            ttft_ms: output.ttft_ms,
            total_ms: Some(output.total_ms),
            tokens_per_sec: output.tokens_per_sec,
            passed,
            error: None,
        },
    );
}

fn emit_event(app: &AppHandle, event: ProgressEvent) {
    let _ = app.emit(EVENT_PROGRESS, event);
}

fn now_millis() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

