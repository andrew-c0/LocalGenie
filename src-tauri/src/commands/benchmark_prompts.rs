const MAX_NAME_CHARS: usize = 120;
const MAX_DESCRIPTION_CHARS: usize = 2000;
const MAX_TEXT_CHARS: usize = 20_000;
const MAX_KEYWORDS: usize = 50;
const MAX_KEYWORD_CHARS: usize = 100;
const MAX_FILES_PER_PROMPT: usize = 10;

/// A saved prompt with its keywords and attached files, in the order they were saved.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkPromptDto {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
    pub text: String,
    pub match_rule: String,
    pub keywords: Vec<String>,
    pub files: Vec<BenchmarkFileDto>,
    /// Runs since the prompt was last saved.
    pub run_count: i64,
    pub created_at: i64,
    pub updated_at: i64,
}

/// What the editor sends. The id is generated by the frontend, so a save is an upsert.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BenchmarkPromptInput {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
    pub text: String,
    pub match_rule: String,
    pub keywords: Vec<String>,
    pub file_ids: Vec<String>,
}

/// Input after trimming and checking. Keywords are unique (case-insensitive) and files are unique.
#[derive(Debug, Clone, PartialEq)]
struct ValidPrompt {
    id: String,
    name: String,
    description: Option<String>,
    text: String,
    match_rule: String,
    keywords: Vec<String>,
    file_ids: Vec<String>,
}

#[tauri::command]
pub async fn list_benchmark_prompts(
    db: State<'_, DatabaseConnection>,
) -> Result<Vec<BenchmarkPromptDto>, String> {
    list_prompts(&db).await
}

#[tauri::command]
pub async fn save_benchmark_prompt(
    app: AppHandle,
    db: State<'_, DatabaseConnection>,
    prompt: BenchmarkPromptInput,
) -> Result<BenchmarkPromptDto, String> {
    let root = store_root(&app)?;
    save_prompt(&db, &root, prompt).await
}

#[tauri::command]
pub async fn delete_benchmark_prompt(
    app: AppHandle,
    db: State<'_, DatabaseConnection>,
    id: String,
) -> Result<(), String> {
    let root = store_root(&app)?;
    delete_prompt(&db, &root, &id).await
}

async fn list_prompts(db: &DatabaseConnection) -> Result<Vec<BenchmarkPromptDto>, String> {
    let prompts = benchmark_prompt::Entity::find()
        .order_by_asc(benchmark_prompt::Column::Name)
        .all(db)
        .await
        .map_err(|e| e.to_string())?;
    let mut out = Vec::with_capacity(prompts.len());
    for prompt in prompts {
        out.push(load_prompt(db, prompt).await?);
    }
    Ok(out)
}

async fn load_prompt(
    db: &DatabaseConnection,
    prompt: benchmark_prompt::Model,
) -> Result<BenchmarkPromptDto, String> {
    let keywords = benchmark_prompt_keyword::Entity::find()
        .filter(benchmark_prompt_keyword::Column::PromptId.eq(&prompt.id))
        .order_by_asc(benchmark_prompt_keyword::Column::Position)
        .all(db)
        .await
        .map_err(|e| e.to_string())?
        .into_iter()
        .map(|k| k.keyword)
        .collect();

    let file_links = benchmark_prompt_file::Entity::find()
        .filter(benchmark_prompt_file::Column::PromptId.eq(&prompt.id))
        .order_by_asc(benchmark_prompt_file::Column::Position)
        .all(db)
        .await
        .map_err(|e| e.to_string())?;
    let file_ids: Vec<String> = file_links.into_iter().map(|l| l.file_id).collect();
    let mut files = Vec::with_capacity(file_ids.len());
    for id in &file_ids {
        // A link always points at a row (restrict foreign key), so a missing row is a bug.
        let row = benchmark_file::Entity::find_by_id(id.as_str())
            .one(db)
            .await
            .map_err(|e| e.to_string())?
            .ok_or_else(|| format!("benchmark file {id} is missing"))?;
        files.push(row.into());
    }

    Ok(BenchmarkPromptDto {
        id: prompt.id,
        name: prompt.name,
        description: prompt.description,
        text: prompt.text,
        match_rule: prompt.match_rule,
        run_count: prompt.run_count,
        keywords,
        files,
        created_at: prompt.created_at,
        updated_at: prompt.updated_at,
    })
}

/// Create or replace a prompt. Files dropped by this save are removed from disk when no other
/// prompt or step uses them. Testable core of `save_benchmark_prompt`.
pub(super) async fn save_prompt(
    db: &DatabaseConnection,
    root: &Path,
    input: BenchmarkPromptInput,
) -> Result<BenchmarkPromptDto, String> {
    let valid = validate(input)?;
    let now = now_millis();

    let previous_files: Vec<String> = benchmark_prompt_file::Entity::find()
        .filter(benchmark_prompt_file::Column::PromptId.eq(&valid.id))
        .all(db)
        .await
        .map_err(|e| e.to_string())?
        .into_iter()
        .map(|l| l.file_id)
        .collect();
    let existing = benchmark_prompt::Entity::find_by_id(valid.id.as_str())
        .one(db)
        .await
        .map_err(|e| e.to_string())?;

    let txn = db.begin().await.map_err(|e| e.to_string())?;

    let head = benchmark_prompt::ActiveModel {
        id: Set(valid.id.clone()),
        name: Set(valid.name.clone()),
        description: Set(valid.description.clone()),
        text: Set(valid.text.clone()),
        match_rule: Set(valid.match_rule.clone()),
        // Saving is an edit, so the run counter starts again.
        run_count: Set(0),
        created_at: Set(existing.as_ref().map_or(now, |p| p.created_at)),
        updated_at: Set(now),
    };
    if existing.is_some() {
        head.update(&txn).await.map_err(|e| e.to_string())?;
    } else {
        head.insert(&txn).await.map_err(|e| e.to_string())?;
    }

    // Keywords and file links are replaced as a set, so their order is the saved order.
    benchmark_prompt_keyword::Entity::delete_many()
        .filter(benchmark_prompt_keyword::Column::PromptId.eq(&valid.id))
        .exec(&txn)
        .await
        .map_err(|e| e.to_string())?;
    for (position, keyword) in valid.keywords.iter().enumerate() {
        benchmark_prompt_keyword::ActiveModel {
            prompt_id: Set(valid.id.clone()),
            position: Set(position as i32),
            keyword: Set(keyword.clone()),
        }
        .insert(&txn)
        .await
        .map_err(|e| e.to_string())?;
    }

    benchmark_prompt_file::Entity::delete_many()
        .filter(benchmark_prompt_file::Column::PromptId.eq(&valid.id))
        .exec(&txn)
        .await
        .map_err(|e| e.to_string())?;
    for (position, file_id) in valid.file_ids.iter().enumerate() {
        let known = benchmark_file::Entity::find_by_id(file_id.as_str())
            .one(&txn)
            .await
            .map_err(|e| e.to_string())?
            .is_some();
        if !known {
            return Err("A file is no longer in the library. Remove it and try again.".to_string());
        }
        benchmark_prompt_file::ActiveModel {
            prompt_id: Set(valid.id.clone()),
            position: Set(position as i32),
            file_id: Set(file_id.clone()),
        }
        .insert(&txn)
        .await
        .map_err(|e| e.to_string())?;
    }

    txn.commit().await.map_err(|e| e.to_string())?;

    let dropped: Vec<String> = previous_files
        .into_iter()
        .filter(|id| !valid.file_ids.contains(id))
        .collect();
    remove_if_unreferenced(db, root, &dropped).await?;

    let saved = benchmark_prompt::Entity::find_by_id(valid.id.as_str())
        .one(db)
        .await
        .map_err(|e| e.to_string())?
        .ok_or_else(|| "prompt was not saved".to_string())?;
    load_prompt(db, saved).await
}

/// Delete a prompt, unless a suite uses it. Its files are removed when nothing else uses them.
pub(super) async fn delete_prompt(db: &DatabaseConnection, root: &Path, id: &str) -> Result<(), String> {
    let step_rows = benchmark_suite_step::Entity::find()
        .filter(benchmark_suite_step::Column::PromptId.eq(id))
        .all(db)
        .await
        .map_err(|e| e.to_string())?;
    if !step_rows.is_empty() {
        let mut suite_ids: Vec<String> = step_rows.into_iter().map(|s| s.suite_id).collect();
        suite_ids.sort();
        suite_ids.dedup();
        let names: Vec<String> = benchmark_suite::Entity::find()
            .filter(benchmark_suite::Column::Id.is_in(suite_ids))
            .all(db)
            .await
            .map_err(|e| e.to_string())?
            .into_iter()
            .map(|s| s.name)
            .collect();
        return Err(format!(
            "This prompt is used by {}. Remove it from those suites first.",
            names.join(", ")
        ));
    }

    let previous_files: Vec<String> = benchmark_prompt_file::Entity::find()
        .filter(benchmark_prompt_file::Column::PromptId.eq(id))
        .all(db)
        .await
        .map_err(|e| e.to_string())?
        .into_iter()
        .map(|l| l.file_id)
        .collect();

    let result = benchmark_prompt::Entity::delete_by_id(id)
        .exec(db)
        .await
        .map_err(|e| e.to_string())?;
    if result.rows_affected == 0 {
        return Err("This prompt no longer exists.".to_string());
    }

    remove_if_unreferenced(db, root, &previous_files).await
}

fn validate(input: BenchmarkPromptInput) -> Result<ValidPrompt, String> {
    let id = input.id.trim().to_string();
    if id.is_empty() {
        return Err("A prompt id is required.".to_string());
    }

    let name = input.name.trim().to_string();
    if name.is_empty() {
        return Err("Give the prompt a name.".to_string());
    }
    if name.chars().count() > MAX_NAME_CHARS {
        return Err(format!("The name can be at most {MAX_NAME_CHARS} characters."));
    }

    let description = input
        .description
        .map(|d| d.trim().to_string())
        .filter(|d| !d.is_empty());
    if description
        .as_ref()
        .is_some_and(|d| d.chars().count() > MAX_DESCRIPTION_CHARS)
    {
        return Err(format!(
            "The description can be at most {MAX_DESCRIPTION_CHARS} characters."
        ));
    }

    let text = input.text.trim().to_string();
    if text.is_empty() {
        return Err("Write the prompt text that is sent to the model.".to_string());
    }
    if text.chars().count() > MAX_TEXT_CHARS {
        return Err(format!("The prompt text can be at most {MAX_TEXT_CHARS} characters."));
    }

    let match_rule = input.match_rule;
    if match_rule != "all" && match_rule != "any" {
        return Err("The keyword rule must be 'all' or 'any'.".to_string());
    }

    let mut keywords: Vec<String> = Vec::new();
    for raw in input.keywords {
        let keyword = raw.trim();
        if keyword.is_empty() {
            continue;
        }
        if keyword.chars().count() > MAX_KEYWORD_CHARS {
            return Err(format!(
                "A keyword can be at most {MAX_KEYWORD_CHARS} characters."
            ));
        }
        let lower = keyword.to_lowercase();
        if keywords.iter().any(|k| k.to_lowercase() == lower) {
            continue;
        }
        keywords.push(keyword.to_string());
    }
    if keywords.len() > MAX_KEYWORDS {
        return Err(format!("A prompt can have at most {MAX_KEYWORDS} keywords."));
    }

    let mut file_ids: Vec<String> = Vec::new();
    for id in input.file_ids {
        if !file_ids.contains(&id) {
            file_ids.push(id);
        }
    }
    if file_ids.len() > MAX_FILES_PER_PROMPT {
        return Err(format!(
            "A prompt can have at most {MAX_FILES_PER_PROMPT} files."
        ));
    }

    Ok(ValidPrompt {
        id,
        name,
        description,
        text,
        match_rule,
        keywords,
        file_ids,
    })
}

fn now_millis() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::super::benchmark_files::{import_file, sweep_orphans};
    use super::super::benchmark_files::tests::TempStore;
    use super::*;
    use crate::entities::benchmark_run;

    use std::fs;

    fn input(id: &str, file_ids: &[&str]) -> BenchmarkPromptInput {
        BenchmarkPromptInput {
            id: id.into(),
            name: "Capital".into(),
            description: None,
            text: "What is the capital of France?".into(),
            match_rule: "all".into(),
            keywords: vec!["Paris".into(), " paris ".into(), "".into(), "Berlin".into()],
            file_ids: file_ids.iter().map(|s| s.to_string()).collect(),
        }
    }

    #[test]
    fn validate_trims_dedupes_and_drops_blank_keywords() {
        let valid = validate(input("p1", &["f1", "f1"])).expect("valid");
        assert_eq!(valid.keywords, vec!["Paris".to_string(), "Berlin".to_string()]);
        assert_eq!(valid.file_ids, vec!["f1".to_string()]);
        assert_eq!(valid.description, None);
    }

    #[test]
    fn validate_rejects_bad_rule_name_and_limits() {
        let mut bad_rule = input("p1", &[]);
        bad_rule.match_rule = "some".into();
        assert!(validate(bad_rule).is_err());

        let mut no_name = input("p1", &[]);
        no_name.name = "   ".into();
        assert!(validate(no_name).is_err());

        let mut too_many = input("p1", &[]);
        too_many.keywords = (0..=MAX_KEYWORDS).map(|i| format!("k{i}")).collect();
        assert!(validate(too_many).is_err());
    }

    #[tokio::test]
    async fn save_then_list_returns_keywords_and_files_in_order() {
        let store = TempStore::new("save");
        let db = store.db().await;
        let src = store.write("notes.txt", "one two three");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");

        let saved = save_prompt(&db, &store.root(), input("p1", &["f1"]))
            .await
            .expect("save");
        assert_eq!(saved.keywords, vec!["Paris".to_string(), "Berlin".to_string()]);
        assert_eq!(saved.files.len(), 1);
        assert_eq!(saved.files[0].id, "f1");

        let listed = list_prompts(&db).await.expect("list");
        assert_eq!(listed.len(), 1);
        assert_eq!(listed[0].keywords, saved.keywords);
        assert_eq!(listed[0].files[0].chars, Some(13));
    }

    #[tokio::test]
    async fn saving_without_a_file_removes_its_copy() {
        let store = TempStore::new("drop-file");
        let db = store.db().await;
        let src = store.write("notes.txt", "x");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");
        save_prompt(&db, &store.root(), input("p1", &["f1"]))
            .await
            .expect("save with file");

        save_prompt(&db, &store.root(), input("p1", &[]))
            .await
            .expect("save without file");

        assert!(!store.root().join("f1").exists());
        assert!(list_prompts(&db).await.expect("list")[0].files.is_empty());
    }

    #[tokio::test]
    async fn deleting_an_unused_prompt_removes_its_files() {
        let store = TempStore::new("delete");
        let db = store.db().await;
        let src = store.write("notes.txt", "x");
        import_file(&db, &store.root(), &src, "f1").await.expect("import");
        save_prompt(&db, &store.root(), input("p1", &["f1"]))
            .await
            .expect("save");

        delete_prompt(&db, &store.root(), "p1").await.expect("delete");

        assert!(list_prompts(&db).await.expect("list").is_empty());
        assert!(!store.root().join("f1").exists());
        assert!(benchmark_file::Entity::find_by_id("f1")
            .one(&db)
            .await
            .expect("query")
            .is_none());
    }

    #[tokio::test]
    async fn a_prompt_used_by_a_suite_cannot_be_deleted() {
        let store = TempStore::new("in-use");
        let db = store.db().await;
        save_prompt(&db, &store.root(), input("p1", &[]))
            .await
            .expect("save");
        benchmark_suite::ActiveModel {
            id: Set("s1".into()),
            name: Set("Smoke".into()),
            description: Set(None),
            mode: Set("independent".into()),
            warmup_runs: Set(0),
            repetitions: Set(1),
            run_count: Set(0),
            created_at: Set(1),
            updated_at: Set(1),
        }
        .insert(&db)
        .await
        .expect("suite");
        benchmark_suite_step::ActiveModel {
            id: Set("st1".into()),
            suite_id: Set("s1".into()),
            position: Set(0),
            prompt_id: Set("p1".into()),
        }
        .insert(&db)
        .await
        .expect("step");

        let err = delete_prompt(&db, &store.root(), "p1")
            .await
            .expect_err("in use");
        assert!(err.contains("Smoke"), "names the suite: {err}");
        assert_eq!(list_prompts(&db).await.expect("list").len(), 1);
    }

    #[tokio::test]
    async fn a_run_keeps_its_record_when_the_prompt_is_deleted() {
        let store = TempStore::new("run-history");
        let db = store.db().await;
        save_prompt(&db, &store.root(), input("p1", &[]))
            .await
            .expect("save");
        benchmark_run::ActiveModel {
            id: Set("r1".into()),
            suite_id: Set(None),
            suite_name: Set("Old".into()),
            model_name: Set("org/model".into()),
            model_key: Set("org/model".into()),
            compute: Set("cpu".into()),
            mode: Set("independent".into()),
            warmup_runs: Set(0),
            repetitions: Set(1),
            status: Set("completed".into()),
            started_at: Set(1),
            ..Default::default()
        }
        .insert(&db)
        .await
        .expect("run");

        delete_prompt(&db, &store.root(), "p1").await.expect("delete");

        assert!(benchmark_run::Entity::find_by_id("r1")
            .one(&db)
            .await
            .expect("query")
            .is_some());
    }

    #[tokio::test]
    async fn startup_sweep_leaves_files_that_prompts_use() {
        let store = TempStore::new("sweep-kept");
        let db = store.db().await;
        let src = store.write("notes.txt", "x");
        import_file(&db, &store.root(), &src, "kept").await.expect("import");
        save_prompt(&db, &store.root(), input("p1", &["kept"]))
            .await
            .expect("save");
        fs::create_dir_all(store.root().join("stray")).expect("stray");

        let removed = sweep_orphans(&db, &store.root()).await.expect("sweep");

        assert_eq!(removed, 1);
        assert!(store.root().join("kept").join("notes.txt").is_file());
    }
}
